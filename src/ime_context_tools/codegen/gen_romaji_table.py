"""Generate `crates/ime-lexicon/src/romaji_table.rs` from the romkan2 package.

romkan2's `to_hiragana` substitutes an ordered regex alternation of literal
romaji patterns; first match wins at each position. Emitting the table in that
exact order lets the Rust scanner reproduce `re.sub` semantics with plain
`starts_with` checks. Run whenever romkan2 is upgraded; the output is
committed so builds never depend on Python.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from romkan2 import ROMKAN_H
from romkan2.common import ROMPAT_H

HEADER = '''\
//! Ordered romaji -> hiragana table extracted from romkan2 {version}.
//!
//! GENERATED by `python -m ime_context_tools.codegen.gen_romaji_table` —
//! do not edit by hand. First match at each position wins, mirroring the
//! regex alternation order of `romkan2.common.ROMPAT_H`.

pub static ROMAJI_TO_HIRAGANA: &[(&str, &str)] = &[
'''


def main(argv: list[str] | None = None) -> int:
    from importlib.metadata import version

    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).parents[4]
        / "ime-context-core"
        / "crates"
        / "ime-lexicon"
        / "src"
        / "romaji_table.rs",
    )
    args = parser.parse_args(argv)

    ordered = ROMPAT_H.pattern.split("|")
    assert set(ordered) == set(ROMKAN_H), "pattern alternatives must cover the mapping"
    lines = [HEADER.format(version=version("romkan2"))]
    for pattern in ordered:
        lines.append(f'    ("{pattern}", "{ROMKAN_H[pattern]}"),\n')
    lines.append("];\n")
    args.output.write_text("".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {args.output} ({len(ordered)} patterns)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
